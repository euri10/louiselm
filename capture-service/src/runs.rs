/// Durable Run state retained after cleanup for Forensics correlation.
#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
pub struct Run {
    /// Storage schema version.
    pub schema_version: u8,
    /// Monotonic durable revision used by invalidation clients.
    pub revision: u64,
    /// Run UUID.
    pub id: String,
    /// Session identity used to form a truthful reaper actor.
    pub session_id: Option<String>,
    /// Configured Agent name used to reload the ACP Session.
    pub agent: Option<String>,
    /// Agent-side ACP Session identifier.
    pub acp_session_id: Option<String>,
    /// Working directory used when reloading the ACP Session.
    pub working_dir: Option<String>,
    /// Whether admission confirmed ACP `session/load` support.
    pub load_session: Option<bool>,
    /// One of `admitted`, `active`, `parked`, `cold_parked`, `resuming`, or `disposed`.
    pub state: String,
    /// Relative Park expiry declared at admission.
    pub park_ttl_ms: u64,
    /// Time when the current Park began.
    pub parked_at_ms: Option<u64>,
    /// Cold-Park expiry.
    pub park_expires_at_ms: u64,
    /// Mutation refused when generated-work exhaustion triggered this Park.
    pub triggering_mutation_id: Option<String>,
    resume_attempt: Option<ResumeAttempt>,
    /// Run-wide generated-work accounting.
    pub generated_work: GeneratedWorkBudget,
    generate_token_sha256: String,
    cleanup: Vec<CleanupEntry>,
}

/// Non-sensitive authoritative Run projection for local observers.
#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
pub struct RunView {
    /// Run UUID.
    pub id: String,
    /// Monotonic durable revision for optimistic concurrency.
    pub revision: u64,
    /// Durable lifecycle state, as in [`Run::state`].
    pub state: String,
    /// Agent-scoped actor, when a Session is attached.
    pub session_id: Option<String>,
    /// Operator-approved absolute capacity ceiling.
    pub generated_work_ceiling: u64,
    /// Capacity consumed by confirmed outputs.
    pub generated_work_consumed: u64,
    /// Capacity held for pending mutations.
    pub generated_work_reserved: u64,
    /// Mutations awaiting reconciliation.
    pub pending_mutation_ids: Vec<String>,
    /// Refused mutation that caused the Run to Park.
    pub triggering_mutation_id: Option<String>,
    /// Park expiry as Unix epoch milliseconds; zero when no expiry is set.
    pub park_expires_at_ms: u64,
    /// Most recent resume attempt's stable identifier, if any.
    pub resume_operation_id: Option<String>,
    /// Resume lease deadline as Unix epoch milliseconds, if any.
    pub resume_deadline_ms: Option<u64>,
}

impl Run {
    /// Resolve a confirmed generated issue by mutation identity.
    #[must_use]
    pub fn generated_issue(&self, mutation_id: &str) -> Option<&str> {
        self.generated_work
            .outputs
            .iter()
            .find(|output| output.mutation_id == mutation_id)
            .map(|output| output.external_id.as_str())
    }
}

